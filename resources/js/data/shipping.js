export const DEFAULT_SHIPPING = { karachi: 700, other: 1700 };

export function resolveShippingRates(settings = {}) {
    return {
        karachi: Math.max(0, Number(settings.shipping_karachi ?? DEFAULT_SHIPPING.karachi) || 0),
        other: Math.max(0, Number(settings.shipping_other ?? DEFAULT_SHIPPING.other) || 0),
    };
}

export function isKarachiCity(city = '') {
    const normalized = String(city).trim().toLowerCase().replace(/\s+/g, ' ');
    return normalized === 'karachi' || normalized === 'khi' || normalized.startsWith('karachi');
}

export function shippingForCity(city, rates = DEFAULT_SHIPPING) {
    if (!city) return 0;
    return isKarachiCity(city) ? Number(rates.karachi || 0) : Number(rates.other || 0);
}
